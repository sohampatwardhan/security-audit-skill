"""Generate the human- and agent-facing documents for a ``.security-audit`` folder.

``README.md`` is an executive summary rebuilt from every area's ``latest.json`` beside it;
``AGENTS.md`` tells agents how to work with those findings. Both are derived only from reports that
were already redacted when written, so no credential value can enter them.
"""

from __future__ import annotations

import html
import json
from pathlib import Path
import re
from typing import Any, Iterable

SECURITY_DIR_NAME = ".security-audit"
_MAX_LISTED = 10
_BLOCKING = {"block", "blocked"}

_AREA_NAME = re.compile(r"[A-Za-z0-9._-]+")
_MARKDOWN_CONTROL = re.compile(r"([\\`*_{}\[\]()#+.!|>~-])")
_MODES = {"change", "main", "release"}

_STATUS_RANK = {"blocked": 0, "unavailable": 1, "invalid": 2, "warnings": 3, "pass": 4}

GITIGNORE = """# Generated by security-audit-skill. This folder may be committed publicly; credentials must not be.
# Reports and the README/AGENTS documents are safe to publish. Anything below is not.
private/
raw/
.env
.env.*
*.pem
*.key
*.p12
*.pfx
*.token
*.secret
*.secrets
credentials*
secrets*
"""

AGENTS_MD = """# AGENTS.md

Instructions for AI agents working with the security audit evidence in this folder. Everything
here is generated by `security-audit-skill`; treat it as evidence, not as a place to edit by hand.

## Layout

- `README.md` – executive summary of the latest result for every audited area. Regenerated on each
  audit; do not edit.
- `<area>/latest.json` – authoritative machine-readable report for the area. Prefer it over any
  prose summary.
- `<area>/latest.md` – the same evidence for human review.
- `<area>/audit-<timestamp>.json|md` – immutable evidence kept for main and release runs. Never
  modify or delete these.

## Reading results

1. Start from `README.md`, then confirm the details in the area's `latest.json`.
2. `status` is one of `pass`, `warnings`, `blocked`, `unavailable`, `invalid`. Only `pass` means no
   action is needed. `warnings` still needs review and is never "clean". `unavailable` means required
   evidence is missing, so the result says nothing about whether the project is safe.
3. Check `sources` for gaps (`partial`, `unavailable`, stale) before trusting an empty findings list.

## Working with findings

- Fix the cause, then re-run the audit; do not edit reports to change a result.
- Apply only fixes the report names. Do not assume a newer version or a suppression is safe.
- Ask the user before major-version upgrades, dependency replacements, or accepting a risk.
- Record accepted risk and mitigation through the audit's acceptance and policy inputs, never by
  deleting a finding. Accepted risk cannot downgrade a block or a known-exploited result.
- Never print, copy, or commit secret values. Reports reference secrets by location and fingerprint
  only; keep it that way.
- Re-run the relevant audit after every fix, and run a fresh `main` or `release` audit at the
  matching delivery gate.

## Publication safety

This folder may be committed to a public repository, so treat everything in it as public.

- Credentials never belong here. Pass them only as environment-variable names. If a tool must keep
  raw output that may contain credentials, write it under `private/` or `raw/`; the generated
  `.gitignore` excludes those paths and credential-style files. Do not weaken or delete that
  `.gitignore`, and never `git add -f` an ignored file.
- Never add secret values, credentials, internal hostnames or URLs, local absolute paths, or personal
  data to anything that ends up here, including acceptance, mitigation, and reachability evidence text.
- Unpatched `blocked` findings in a public repository disclose a known weakness. Prefer fixing or
  mitigating before publishing, and ask the user before committing a report that still shows one.
- Do not commit files here that the audit did not generate.

## Staleness

A report describes one revision at one time. If the revision, lockfile, or code has changed since
the `timestamp` and `project_revision` in `latest.json`, treat the result as stale and re-run.
"""


def refresh_folder_docs(security_dir: Path) -> tuple[tuple[Path, str], ...]:
    """Return ``(path, text)`` pairs for the folder README, AGENTS, and credential .gitignore files.

    Args:
        security_dir: A ``.security-audit`` directory whose subdirectories hold ``latest.json``.
    """
    reports = _load_reports(security_dir)
    return (
        (security_dir / "README.md", _render_readme(reports)),
        (security_dir / "AGENTS.md", AGENTS_MD),
        (security_dir / ".gitignore", GITIGNORE),
    )


def is_security_dir(path: Path) -> bool:
    """Report whether ``path`` is a ``.security-audit`` folder that should carry these documents."""
    return Path(path).name == SECURITY_DIR_NAME


def _load_reports(security_dir: Path) -> list[tuple[str, dict[str, Any]]]:
    reports: list[tuple[str, dict[str, Any]]] = []
    for child in sorted(security_dir.iterdir()):
        latest = child / "latest.json"
        if not _AREA_NAME.fullmatch(child.name) or not child.is_dir() or not latest.is_file():
            continue
        try:
            data = json.loads(latest.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            reports.append((child.name, {"gate_status": "invalid", "_unreadable": True}))
            continue
        if isinstance(data, dict):
            reports.append((child.name, data))
    return reports


def _render_readme(reports: Iterable[tuple[str, dict[str, Any]]]) -> str:
    items = sorted(reports, key=lambda item: (_STATUS_RANK.get(_status(item[1]), 9), item[0]))
    lines = ["# Security audit summary", ""]
    if not items:
        lines += ["No audit reports found yet. Run an audit to populate this folder.", ""]
        return "\n".join(lines)

    worst = _status(items[0][1])
    lines += [
        f"**Overall: {worst.upper()}.** {_headline(worst)}",
        "",
        "| Area | Status | Mode | Revision | Audited | Blocking | Warnings | Source gaps |",
        "|---|---|---|---|---|---:|---:|---:|",
    ]
    for area, data in items:
        counts = _decision_counts(data)
        lines.append(
            f"| [{area}]({area}/latest.md) | {_status(data)} | {_mode(data)} | "
            f"{_text(data.get('project_revision')) or '-'} | {_text(data.get('timestamp')) or '-'} | "
            f"{counts['blocking']} | {counts['warnings']} | {len(_source_gaps(data))} |"
        )
    lines.append("")

    for area, data in items:
        top = _top_findings(data)
        gaps = _source_gaps(data)
        if not top and not gaps and _status(data) == "pass":
            continue
        lines += [f"## {area}", ""]
        if top:
            lines += ["Highest-priority findings:", ""]
            lines += [f"- {entry}" for entry in top]
            lines.append("")
        if gaps:
            lines += ["Source gaps:", ""]
            lines += [f"- {gap}" for gap in gaps]
            lines.append("")
        lines += [f"Details: [{area}/latest.md]({area}/latest.md)", ""]

    lines += [
        "Generated from each area's `latest.json`. Do not edit; see [AGENTS.md](AGENTS.md) for how to "
        "work with these findings. This folder may be published: it holds no credential values, but "
        "review unpatched blocking findings before committing it to a public repository.",
        "",
    ]
    return "\n".join(lines)


def _status(data: dict[str, Any]) -> str:
    value = data.get("gate_status")
    return value if isinstance(value, str) and value in _STATUS_RANK else "invalid"


def _mode(data: dict[str, Any]) -> str:
    value = data.get("mode")
    return value if value in _MODES else "-"


def _headline(status: str) -> str:
    return {
        "blocked": "At least one finding blocks delivery.",
        "unavailable": "Required evidence is missing, so safety is not established.",
        "invalid": "A report or its configuration is invalid.",
        "warnings": "No blocks, but warnings or gaps need review; this is not a clean result.",
        "pass": "Required evidence is complete and nothing needs action.",
    }.get(status, "Status could not be determined.")


def _decision_counts(data: dict[str, Any]) -> dict[str, int]:
    decisions = data.get("decisions") if isinstance(data.get("decisions"), list) else []
    blocking = sum(1 for item in decisions if isinstance(item, dict) and item.get("decision") in _BLOCKING)
    warnings = sum(1 for item in decisions if isinstance(item, dict) and item.get("decision") == "warn")
    return {"blocking": blocking, "warnings": warnings}


def _source_gaps(data: dict[str, Any]) -> list[str]:
    sources = data.get("sources") if isinstance(data.get("sources"), list) else []
    return [
        f"{_text(item.get('source'))}: {_text(item.get('state'))}"
        for item in sources
        if isinstance(item, dict) and item.get("state") in {"partial", "unavailable"}
    ]


def _top_findings(data: dict[str, Any]) -> list[str]:
    findings = data.get("findings") if isinstance(data.get("findings"), list) else []
    order = {"critical": 0, "high": 1, "medium": 2, "low": 3, "unknown": 4}
    ranked: list[tuple[int, int, str]] = []
    for item in findings:
        if not isinstance(item, dict):
            continue
        advisory = item.get("advisory") if isinstance(item.get("advisory"), dict) else {}
        package = item.get("package") if isinstance(item.get("package"), dict) else {}
        if advisory.get("withdrawn"):
            continue
        raw = advisory.get("severity")
        severity = raw if raw in order else "unknown"
        kev = bool(item.get("kev"))
        label = (
            f"**{severity}**{' (known exploited)' if kev else ''} {_text(advisory.get('id'))} in "
            f"{_text(package.get('purl')) or _text(package.get('name'))}"
        )
        ranked.append((0 if kev else 1, order.get(severity, 4), label))
    ranked.sort()
    extra = len(ranked) - _MAX_LISTED
    listed = [label for _kev, _sev, label in ranked[:_MAX_LISTED]]
    if extra > 0:
        listed.append(f"... and {extra} more in `latest.json`")
    return listed


def _text(value: Any) -> str:
    """Flatten, HTML-escape, and Markdown-escape untrusted report text, as ``latest.md`` does."""
    if value is None:
        return ""
    flat = " ".join(str(value).split())
    return _MARKDOWN_CONTROL.sub(r"\\\1", html.escape(flat, quote=True))
